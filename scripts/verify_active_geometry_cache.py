def main() -> None:
    db = BookDatabase()
    for page_num, (feynman, misconception) in PEDAGOGY.items():
        page = db.get_page(BOOK_ID, page_num)
        if page is None:
            raise RuntimeError(f"У кеші немає друкованої сторінки {page_num}")
        if not page.ocr_ru.strip() or not page.translation_uk.strip():
            raise RuntimeError(f"Сторінка {page_num} не має повного OCR або перекладу")
        page.translation_uk = page.translation_uk.replace("\\n", "\n")
        page.feynman_notes = page.feynman_notes.strip() or feynman
        page.misconceptions = page.misconceptions.strip() or misconception
        page.status = "verified"
        db.save_page(page)


if __name__ == "__main__":
    main()
